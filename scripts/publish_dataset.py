def count(path: Path) -> tuple[int, Counter]:
    origins = Counter(json.loads(line)["origin"] for line in path.open(encoding="utf-8"))
    return sum(origins.values()), origins


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-id", default="Lahad/wolof-normalization-pairs")
    parser.add_argument("--private", action="store_true")
    args = parser.parse_args()

    if STAGING.exists():
        shutil.rmtree(STAGING)
    (STAGING / "data").mkdir(parents=True)
    for source, target in [("train", "train"), ("dev", "validation"), ("test", "test")]:
        shutil.copy(DATA / f"{source}.jsonl", STAGING / "data" / f"{target}.jsonl")

    train, origins = count(DATA / "train.jsonl")
    card = CARD.format(
        train=f"{train:,}",
        train_origins=", ".join(f"{n:,} {o}" for o, n in origins.most_common()),
        validation=count(DATA / "dev.jsonl")[0],
        test=count(DATA / "test.jsonl")[0],
    )
    (STAGING / "README.md").write_text(card, encoding="utf-8")

    api = HfApi()
    api.create_repo(args.repo_id, repo_type="dataset", private=args.private, exist_ok=True)
    api.upload_folder(folder_path=STAGING, repo_id=args.repo_id, repo_type="dataset",
                      commit_message="Upload Wolof normalization pairs")
    print(f"https://huggingface.co/datasets/{args.repo_id}")


if __name__ == "__main__":
    main()
