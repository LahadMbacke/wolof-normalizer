def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model-dir", required=True, help="dossier « best » produit par train_byt5.py")
    parser.add_argument("--repo-id", default="Lahad/wolof-normalizer-byt5-small")
    parser.add_argument("--dataset", default="Lahad/wolof-normalization-pairs")
    parser.add_argument("--test-wer", type=float, default=11.2)
    parser.add_argument("--dev-wer", type=float, default=9.8)
    parser.add_argument("--private", action="store_true")
    args = parser.parse_args()

    model_dir = Path(args.model_dir)
    if not (model_dir / "config.json").exists():
        raise SystemExit(f"Pas de modèle dans {model_dir} (config.json absent)")

    card = CARD.format(name=args.repo_id.split("/")[-1], repo_id=args.repo_id, dataset=args.dataset,
                       test_wer=args.test_wer, dev_wer=args.dev_wer)
    (model_dir / "README.md").write_text(card, encoding="utf-8")

    api = HfApi()
    api.create_repo(args.repo_id, private=args.private, exist_ok=True)
    api.upload_folder(folder_path=model_dir, repo_id=args.repo_id, ignore_patterns=["training_args.bin"],
                      commit_message="Upload fine-tuned ByT5-small Wolof normalizer")
    print(f"https://huggingface.co/{args.repo_id}")


if __name__ == "__main__":
    main()
